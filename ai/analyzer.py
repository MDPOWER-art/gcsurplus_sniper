import logging
from typing import Optional, Dict, Any
import aiohttp
from pydantic import BaseModel, Field
from google import genai
from google.genai import errors
from google.genai import types
from core.config import GEMINI_API_KEY, MIN_NET_PROFIT_THRESHOLD

logger = logging.getLogger("gcsurplus_sniper.ai")


class DealAnalysis(BaseModel):
    """
    Pydantic Schema for structured deal analysis generated by Gemini 2.0 Flash.
    """

    estimated_resale_value: float = Field(
        ...,
        description="Estimated fair market resale value in CAD (e.g. eBay/secondary market).",
    )
    visual_defects_found: bool = Field(
        ...,
        description=(
            "True if broken screens, cracked displays, torn/severed connectors, "
            "missing vital internal parts, or unrepairable physical damage are observed."
        ),
    )
    defect_details: str = Field(
        default="",
        description="Detailed description of any physical or functional defects identified.",
    )
    confidence_score: float = Field(
        default=0.8,
        description="Confidence score of valuation between 0.0 and 1.0",
    )


class CFOEvaluator:
    """
    Applies CFO financial governance and multimodal AI inspection to auction listings.
    """

    def __init__(self) -> None:
        self.client: Optional[genai.Client] = None
        if GEMINI_API_KEY:
            self.client = genai.Client(api_key=GEMINI_API_KEY)
        else:
            logger.warning("GEMINI_API_KEY not found in environment. AI Analysis will operate in fallback mode.")

    @staticmethod
    def calculate_cfo_net_profit(estimated_value: float, bid_amount: float) -> float:
        """
        CFO Strict Formula:
        Net = (Estimated_Value * 0.85) - (Bid * 1.15) - 15.00
        """
        return (estimated_value * 0.85) - (bid_amount * 1.15) - 15.00

    @staticmethod
    def calculate_suggested_max_bid(estimated_value: float) -> float:
        """
        Calculates maximum bid allowed to guarantee at least MIN_NET_PROFIT_THRESHOLD ($500.00).
        (Estimated_Value * 0.85) - (MaxBid * 1.15) - 15.00 = 500.00
        MaxBid = ((Estimated_Value * 0.85) - 515.00) / 1.15
        """
        target_revenue = (estimated_value * 0.85) - 15.00 - MIN_NET_PROFIT_THRESHOLD
        if target_revenue <= 0:
            return 0.0
        max_bid = target_revenue / 1.15
        return max(0.0, round(max_bid, 2))

    @staticmethod
    def _is_supported_location(location: str) -> bool:
        province = location.strip().rsplit(",", 1)[-1].strip().casefold()
        return province in {"on", "ontario", "qc", "quebec", "québec"}

    async def analyze_listing(
        self,
        listing: Dict[str, Any],
        session: Optional[aiohttp.ClientSession] = None,
    ) -> Dict[str, Any]:
        """
        Executes multimodal AI valuation via Gemini 2.0 Flash and applies strict CFO profit rules.
        """
        title = listing.get("title", "")
        category = listing.get("category", "")
        description = listing.get("description", "")
        current_bid = float(listing.get("current_bid", 0.0))
        minimum_bid = float(listing.get("minimum_bid", 0.0))
        base_cost = max(current_bid, minimum_bid)
        location = str(listing.get("location", "")).strip()
        image_url = listing.get("image_url", "")

        # Default fallback values
        estimated_value = 0.0
        visual_defects = False
        defect_details = ""

        if not self._is_supported_location(location):
            rejection_reason = (
                f"Location outside supported area (Ontario/Quebec) or unknown: "
                f"{location or 'not provided'}"
            )
            return {
                "listing_id": listing.get("id"),
                "estimated_value": estimated_value,
                "cfo_net_profit": round(
                    self.calculate_cfo_net_profit(estimated_value, base_cost), 2
                ),
                "suggested_max_bid": 0.0,
                "is_viable": False,
                "rejection_reason": rejection_reason,
            }

        if self.client:
            try:
                contents = []

                # Download image if present for visual inspection
                if image_url and session:
                    try:
                        async with session.get(image_url, timeout=10) as resp:
                            if resp.status == 200:
                                image_bytes = await resp.read()
                                content_type = resp.headers.get("Content-Type", "image/jpeg")
                                contents.append(
                                    types.Part.from_bytes(
                                        data=image_bytes,
                                        mime_type=content_type,
                                    )
                                )
                    except Exception as img_err:
                        logger.warning(f"Could not download image for visual inspection: {img_err}")

                prompt = (
                    f"You are a professional financial asset valuation expert and technical inspector.\n"
                    f"Analyze this auction lot:\n"
                    f"- Category: {category}\n"
                    f"- Title: {title}\n"
                    f"- Description: {description}\n"
                    f"- Current Bid: ${current_bid:.2f}\n"
                    f"- Minimum Bid: ${minimum_bid:.2f}\n"
                    f"- Cost basis (use max of current bid and minimum bid): "
                    f"${base_cost:.2f}\n"
                    f"- Pickup location: {location}\n\n"
                    f"Task:\n"
                    f"1. Estimate the current market resale value (CAD) on secondary markets (eBay/specialized reseller), "
                    f"and assess profitability against the cost basis of ${base_cost:.2f}, not just the current bid.\n"
                    f"2. Inspect the image and description carefully for visual defects: broken screens, cracked displays, "
                    f"torn/cut connectors, severed cables, or severe physical damage.\n"
                    f"3. Reject any lot outside Ontario or Quebec; the application enforces this rule independently.\n"
                    f"Provide your structured evaluation using the specified schema."
                )
                contents.append(prompt)

                response = await self.client.aio.models.generate_content(
                    model="gemini-3.8-flash",
                    contents=contents,
                    config=types.GenerateContentConfig(
                        response_mime_type="application/json",
                        response_schema=DealAnalysis,
                        temperature=0.2,
                    ),
                )

                if response.parsed:
                    analysis: DealAnalysis = response.parsed
                    estimated_value = analysis.estimated_resale_value
                    visual_defects = analysis.visual_defects_found
                    defect_details = analysis.defect_details
                elif response.text:
                    # Fallback JSON parsing if parsed object unavailable
                    import json
                    raw_data = json.loads(response.text)
                    analysis = DealAnalysis(**raw_data)
                    estimated_value = analysis.estimated_resale_value
                    visual_defects = analysis.visual_defects_found
                    defect_details = analysis.defect_details

            except errors.ClientError as e:
                message = e.message.lower()
                is_quota_or_model_error = (
                    e.code == 429
                    or e.status in {"RESOURCE_EXHAUSTED", "NOT_FOUND"}
                    or (
                        "model" in message
                        and any(term in message for term in ("not found", "unsupported", "not supported"))
                    )
                )
                log = logger.warning if is_quota_or_model_error else logger.error
                log(
                    "Gemini API error for listing %s (code=%s, status=%s); "
                    "continuing CFO evaluation with fallback valuation: %s",
                    listing.get("id"),
                    e.code,
                    e.status,
                    e.message,
                )
            except Exception as e:
                logger.error(f"Gemini AI Analysis failed for listing {listing.get('id')}: {e}")

        # Compute CFO Strict Financial Metrics
        cfo_net_profit = self.calculate_cfo_net_profit(estimated_value, base_cost)
        suggested_max_bid = self.calculate_suggested_max_bid(estimated_value)

        rejection_reasons = []
        if visual_defects:
            rejection_reasons.append(f"Visual defect detected: {defect_details or 'Broken screen/torn connectors'}")
        if cfo_net_profit < MIN_NET_PROFIT_THRESHOLD:
            rejection_reasons.append(f"CFO Net Profit (${cfo_net_profit:.2f}) < threshold (${MIN_NET_PROFIT_THRESHOLD:.2f})")

        is_viable = len(rejection_reasons) == 0 and estimated_value > 0

        rejection_reason = " | ".join(rejection_reasons) if rejection_reasons else None

        return {
            "listing_id": listing.get("id"),
            "estimated_value": round(estimated_value, 2),
            "cfo_net_profit": round(cfo_net_profit, 2),
            "suggested_max_bid": round(suggested_max_bid, 2),
            "is_viable": is_viable,
            "rejection_reason": rejection_reason,
        }


# Global singleton
cfo_evaluator = CFOEvaluator()
